/**
 * Icons are referenced by name from src/lib/data.ts so the content layer stays
 * free of component imports. Registering them explicitly (rather than a
 * dynamic lookup) keeps tree-shaking effective.
 */
const registry = {
  Activity,
  Award,
  Boxes,
  Braces,
  Cloud,
  Container,
  GraduationCap,
  Layers,
  Lock,
  Network,
  Radio,
  Server,
  Shield,
  ShieldCheck,
  Star,
  Terminal,
  Wrench,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof registry;

export function Icon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const Cmp = registry[name as IconName] ?? Boxes;
  return <Cmp className={className} aria-hidden />;
}

